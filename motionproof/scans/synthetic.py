"""SYNTHETIC scan generators with known ground truth, for tests, benchmarks and examples.

Nothing produced here is a measurement of a real part. Files written by these functions carry
``synthetic`` in their name and header.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from numpy.typing import NDArray

from motionproof.core.transforms import axis_angle_matrix

Arr = NDArray[np.float64]


def cylinder_scan(diameter: float, length: float, points: int = 20_000, noise: float = 0.0,
                  seed: int = 0, arc_deg: float = 360.0, outliers: int = 0,
                  ends: bool = True) -> Arr:
    """Points on a cylinder of the given diameter along +Z from the origin (same units)."""
    rng = np.random.default_rng(seed)
    r = diameter / 2
    side_area, end_area = np.pi * diameter * length, np.pi * r * r
    n_end = int(points * end_area / (side_area + 2 * end_area)) if ends else 0
    n_side = points - 2 * n_end
    ang = rng.uniform(0, np.radians(arc_deg), n_side)
    side = np.column_stack([r * np.cos(ang), r * np.sin(ang), rng.uniform(0, length, n_side)])
    side += noise * rng.normal(size=(n_side, 1)) * np.column_stack(
        [np.cos(ang), np.sin(ang), np.zeros(n_side)])
    parts = [side]
    for z in ([0.0, length] if n_end else []):
        rr = r * np.sqrt(rng.uniform(0, 1, n_end))
        a = rng.uniform(0, 2 * np.pi, n_end)
        parts.append(np.column_stack([rr * np.cos(a), rr * np.sin(a),
                                      z + noise * rng.normal(size=n_end)]))
    pts = np.concatenate(parts)
    if outliers:
        lo, hi = pts.min(axis=0) - diameter, pts.max(axis=0) + diameter
        pts = np.concatenate([pts, rng.uniform(lo, hi, size=(outliers, 3))])
    return pts


def rigid(points: Arr, rotation_axis: tuple[float, float, float], angle: float,
          translation: tuple[float, float, float]) -> tuple[Arr, Arr]:
    """Move points by a known pose; returns (moved points, 4x4 transform applied)."""
    t = np.eye(4)
    t[:3, :3] = axis_angle_matrix(rotation_axis, angle)
    t[:3, 3] = translation
    return points @ t[:3, :3].T + t[:3, 3], t


def write_xyz(path: str | Path, points: Arr, units: str, description: str) -> Path:
    p = Path(path)
    if "synthetic" not in p.name:
        raise ValueError("synthetic scan files must have 'synthetic' in their name")
    with p.open("w", encoding="utf-8") as f:
        f.write(f"# SYNTHETIC point cloud generated by MotionProof - not a measurement\n"
                f"# {description}\n# units: {units}\n")
        np.savetxt(f, points, fmt="%.6f")
    return p
