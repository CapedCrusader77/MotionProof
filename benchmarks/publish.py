"""Publish the benchmark package: inputs, raw data, suite run, independent cross-check.

    uv run python benchmarks/publish.py            # all benchmarks
    uv run python benchmarks/publish.py A B G      # a subset (cross-check covers those only)

Steps
1. ``benchmarks/data``: input models (reference design project, single-joint model) and every
   raw SYNTHETIC data set the suite analyses, regenerated with the suite's own seeds.
2. The suite is run (``motionproof.benchmarks.suite``); its full result is saved as
   ``data/suite_results.json`` and the MotionProof outputs the references need as
   ``data/motionproof_outputs.json``.
3. ``reference_calculations.py`` runs in a separate, isolated interpreter (``python -I``) that
   never imports motionproof, and writes ``data/references.json``.
4. Every reference is compared with the suite: closed-form expected values must equal the
   suite's expected values (to 1e-9 relative), independent estimates must agree with
   MotionProof's within the stated tolerance. ``BENCHMARK_RESULTS.md`` is rewritten with the
   suite tables plus the cross-check, and ``data/cross_check.json`` keeps the details.

The exit status is non-zero if any benchmark or any cross-check fails.
"""

from __future__ import annotations

import csv
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

import numpy as np

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"
REPO = ROOT.parent


def _csv(path: Path, header: list[str], columns: list[np.ndarray], comment: str) -> None:
    with path.open("w", newline="", encoding="utf-8") as f:
        f.write(f"# SYNTHETIC data generated by MotionProof - not a measurement. {comment}\n")
        w = csv.writer(f)
        w.writerow(header)
        for row in zip(*columns, strict=True):
            w.writerow([repr(float(v)) if isinstance(v, float | np.floating) else int(v)
                        for v in row])


def export_inputs() -> dict[str, Any]:
    """Write input models and raw data with exactly the suite's generators and seeds."""
    from motionproof.benchmarks import suite
    from motionproof.process.model import BatchPlan, ProcessModel, generate_batch
    from motionproof.reference.nema17_arm import write_reference_project
    from motionproof.scans import synthetic as S

    if DATA.exists():
        shutil.rmtree(DATA)
    DATA.mkdir(parents=True)
    tmp = Path(tempfile.mkdtemp(prefix="mp_pub_"))
    write_reference_project(tmp)
    shutil.copytree(tmp, DATA / "reference_design")
    sj = DATA / "single_joint"
    sj.mkdir()
    (sj / "single.xml").write_text(suite.SINGLE_XML, encoding="utf-8")
    model = suite.single_joint()
    (sj / "model.json").write_text(model.spec.model_dump_json(indent=1, by_alias=True),
                                   encoding="utf-8")

    # A: scan of an 8.030 mm shaft, 5 um noise, known pose
    pts = S.cylinder_scan(8.030, 40.0, 20_000, noise=0.005, seed=3)
    moved, transform = S.rigid(pts, (0.3, 1.0, 0.2), 0.02, (0.4, -0.3, 0.2))
    S.write_xyz(DATA / "A_synthetic_shaft_scan_posed.xyz", moved, "mm",
                "cylinder d=8.030 L=40 mm, 20000 points incl. end faces, noise 0.005 mm, "
                "seed 3, moved by a known rigid transform (see inputs.json)")

    # G: hierarchical process batches
    def feat(name: str, target: float, shared: bool) -> dict[str, Any]:
        return {"feature": name, "process": "CNC turning", "target": target, "unit": "mm",
                "lower_limit": target - 0.05, "upper_limit": target + 0.05, "sources": [
                    {"level": "batch", "std": 0.010, "basis": "specified"},
                    {"level": "setup", "std": 0.006, "basis": "specified",
                     "shared_group": "f1" if shared else None},
                    {"level": "part", "std": 0.004, "basis": "specified"}]}
    pm = ProcessModel.model_validate({"name": "g", "features": [feat("bore", 10.02, False),
                                                                  feat("shaft", 10.0, False)]})
    b = generate_batch(pm, BatchPlan(batches=200, setups_per_batch=6, parts_per_setup=8, seed=1))
    _csv(DATA / "G_synthetic_batch.csv", ["batch", "setup", "part", "bore_mm"],
         [b["batch"], b["setup"], np.arange(b["parts"]), b["actual"]["bore"]],
         "200 batches x 6 setups x 8 parts, seed 1")
    plan = BatchPlan(batches=300, setups_per_batch=5, parts_per_setup=10, seed=3)
    for shared in (False, True):
        pm = ProcessModel.model_validate({"name": "g", "features": [
            feat("bore", 10.02, shared), feat("shaft", 10.0, shared)]})
        bb = generate_batch(pm, plan)
        kind = "shared" if shared else "independent"
        _csv(DATA / f"G_synthetic_clearance_{kind}.csv", ["batch", "setup", "bore_mm", "shaft_mm"],
             [bb["batch"], bb["setup"], bb["actual"]["bore"], bb["actual"]["shaft"]],
             f"300 x 5 x 10, seed 3, setup error {kind}")
    wear = ProcessModel.model_validate({"name": "w", "features": [{
        "feature": "bore", "process": "reaming", "target": 10.0, "unit": "mm",
        "lower_limit": 9.97, "upper_limit": 10.03,
        "sources": [{"level": "part", "std": 0.002, "basis": "specified"}],
        "drift": {"kind": "linear", "rate": 2e-5, "basis": "specified"}}]})
    bw = generate_batch(wear, BatchPlan(parts_per_setup=500, seed=2))
    _csv(DATA / "G_synthetic_tool_wear.csv", ["part", "bore_mm"],
         [np.arange(bw["parts"]), bw["actual"]["bore"]], "linear drift 2e-5 mm/part, seed 2")

    # I: wear progression
    rng = np.random.default_rng(0)
    n = np.linspace(0, 1e6, 25)
    _csv(DATA / "I_synthetic_wear.csv", ["cycles", "backlash_rad"],
         [n, 0.004 + 2e-9 * n + rng.normal(0, 2e-5, 25)],
         "b = 0.004 + 2e-9 n + N(0, 2e-5), seed 0")

    windup = suite.M_ARM * suite.G * suite.L_ARM / 2000.0
    inputs = {
        "note": "Benchmark inputs. All values are benchmark definitions, not measurements; "
                "data files marked SYNTHETIC are generated with known ground truth.",
        "single_joint": {"xml": "single_joint/single.xml", "arm_length": suite.L_ARM,
                         "arm_mass": suite.M_ARM, "ratio": suite.RATIO, "stiffness": 2000.0,
                         "peak_torque": 2.0, "gravity": suite.G},
        "A": {"brep_gap": {"shaft": 9.98, "bore": 10.03, "length": 20.0, "offset": 0.01},
              "scan": {"true_diameter": 8.030, "length": 40.0, "points": 20_000,
                       "noise": 0.005, "seed": 3, "pose_axis": [0.3, 1.0, 0.2],
                       "pose_angle_rad": 0.02, "pose_translation": [0.4, -0.3, 0.2],
                       "transform": transform.tolist()}},
        "B": {"runout": 0.02},
        "C": {"ik_target": None},
        "D": {"backlash": [0.0, 0.005, 0.012], "friction": 0.4, "gravity": False},
        "E": {"offsets_m": [5e-5, 2e-4], "tilts_rad": [1e-3, 2e-3], "seat_change_mm": 0.006},
        "F": {"payloads": [0.0, 0.5, 1.5]},
        "G": {"batch_std": 0.010, "setup_std": 0.006, "part_std": 0.004, "drift_rate": 2e-5},
        "I": {"true_rate": 2e-9, "limit": 0.005, "initial_backlash": 0.004},
        "L": {"backlash": 0.01},
        "M": {"centre": 0.01, "half_width": 0.01, "backlash_limit": 0.016,
              "windup": windup, "scale_lower": 0.2, "scale_upper": 1.0,
              "reliability_target": 0.9, "confidence": 0.9, "unit_cost": 1.0,
              "yield_process": {"mean": 0.01, "std": 0.004}},
    }
    return inputs


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def cross_check(results: list[dict[str, Any]], refs: dict[str, Any]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    by_id = {r["id"]: r for r in results}
    for bid, quantities in refs["expected"].items():
        if bid not in by_id:
            continue
        checks = {c["quantity"]: c for c in by_id[bid]["checks"]}
        for q, ref in quantities.items():
            c = checks.get(q)
            if c is None or c["expected"] is None:
                rows.append({"benchmark": bid, "quantity": q, "kind": "reference value",
                             "reference": ref, "suite": None, "passed": None,
                             "comment": "no matching suite check; reported for context"})
                continue
            ok = abs(ref - c["expected"]) <= 1e-9 * max(1.0, abs(ref))
            rows.append({"benchmark": bid, "quantity": q, "kind": "expected value",
                         "reference": ref, "suite": c["expected"], "passed": bool(ok),
                         "comment": "suite expected value equals independent reference"
                         if ok else "MISMATCH between suite expected value and reference"})
    for bid, items in refs["estimates"].items():
        if bid not in by_id:
            continue
        checks = {c["quantity"]: c for c in by_id[bid]["checks"]}
        for e in items:
            target = e.get("target")
            comp = e.get("compare_with", "")
            if comp.startswith("suite: "):
                c = checks.get(comp[len("suite: "):])
                target = None if c is None else c["actual"]
            if "band" in e:
                lo, hi = e["band"]
                ok = lo - 1e-9 <= e["value"] <= hi + 1e-9
                rows.append({"benchmark": bid, "quantity": e["estimate"], "kind": "estimate",
                             "reference": e["band"], "suite": e["value"], "passed": ok,
                             "comment": "MotionProof choice inside the reference band"})
                continue
            if target is None:
                rows.append({"benchmark": bid, "quantity": e["estimate"], "kind": "estimate",
                             "reference": e["value"], "suite": None, "passed": False,
                             "comment": f"nothing to compare with ({comp})"})
                continue
            lim = e["tolerance_rel"] * max(abs(target), 1e-300) if "tolerance_rel" in e \
                else e["tolerance"]
            ok = abs(e["value"] - target) <= lim
            rows.append({"benchmark": bid, "quantity": e["estimate"], "kind": "estimate",
                         "reference": e["value"], "suite": target, "passed": bool(ok),
                         "comment": f"vs {comp}; |difference| <= {lim:.3g}"})
    return rows


def _fmt(v: Any) -> str:
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.9g}"
    if isinstance(v, list):
        return "[" + ", ".join(_fmt(x) for x in v) + "]"
    return str(v)


def main(keys: list[str]) -> int:
    from motionproof.benchmarks import suite

    inputs = export_inputs()
    results = suite.run(keys or None)
    outputs: dict[str, Any] = {r["id"]: r["outputs"] for r in results if r.get("outputs")}
    if "C" in outputs:
        inputs["C"]["ik_target"] = outputs["C"]["ik_target"]
    (DATA / "inputs.json").write_text(json.dumps(inputs, indent=1), encoding="utf-8")
    (DATA / "motionproof_outputs.json").write_text(
        json.dumps({"C": outputs.get("C", {"fk": []}),
                    "M": outputs.get("M", {"yield_chosen": None, "reciprocal_chosen": None})},
                   indent=1), encoding="utf-8")
    (DATA / "suite_results.json").write_text(json.dumps(results, indent=1, default=str),
                                             encoding="utf-8")
    proc = subprocess.run([sys.executable, "-I", str(ROOT / "reference_calculations.py"),
                           str(DATA)], capture_output=True, text=True, cwd=ROOT)
    if proc.returncode != 0:
        print(proc.stderr, file=sys.stderr)
        return 2
    refs = json.loads((DATA / "references.json").read_text(encoding="utf-8"))
    rows = cross_check(results, refs)
    (DATA / "cross_check.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
    manifest = {str(p.relative_to(DATA)).replace("\\", "/"): _sha(p)
                for p in sorted(DATA.rglob("*")) if p.is_file() and p.name != "MANIFEST.json"}
    (DATA / "MANIFEST.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")

    md = REPO / "BENCHMARK_RESULTS.md"
    suite.write_markdown(results, md)
    graded = [r for r in rows if r["passed"] is not None]
    ok = sum(r["passed"] for r in graded)
    lines = ["", "## Independent cross-check", "",
             "`benchmarks/reference_calculations.py` recomputed the expected values and "
             "re-analysed the raw data in `benchmarks/data` in a separate interpreter that does "
             "not import MotionProof (NumPy, SciPy, PyYAML only). Inputs, raw data, the suite's "
             "full output and the hashes of every file are published there "
             "(`MANIFEST.json`).", "",
             f"Cross-check: **{ok}/{len(graded)} agree**.", "",
             "| Benchmark | Quantity | Kind | Reference | MotionProof | Result | Comment |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        res = "-" if r["passed"] is None else ("agree" if r["passed"] else "DISAGREE")
        lines.append(f"| {r['benchmark']} | {r['quantity']} | {r['kind']} | "
                     f"{_fmt(r['reference'])} | {_fmt(r['suite'])} | {res} | {r['comment']} |")
    lines += ["", "Reproduce: `uv run python benchmarks/publish.py`; references alone: "
              "`python -I benchmarks/reference_calculations.py benchmarks/data`."]
    with md.open("a", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    bench_ok = all(r["status"] in ("PASS", "NOT RUN") for r in results)
    print(f"benchmarks: {sum(r['status'] == 'PASS' for r in results)}/{len(results)} PASS; "
          f"cross-check {ok}/{len(graded)} agree")
    for r in rows:
        if r["passed"] is False:
            print("  DISAGREE", r["benchmark"], r["quantity"], r["reference"], r["suite"])
    return 0 if bench_ok and ok == len(graded) else 1


if __name__ == "__main__":
    sys.path.insert(0, str(REPO))
    raise SystemExit(main(sys.argv[1:]))
